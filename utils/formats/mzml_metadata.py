"""mzML metadata <-> Parquet columns.

Follows the mzPeak draft: run-level metadata goes in the Parquet footer and
per-spectrum metadata in one column per parameter. The footer also holds a
definition for each column (element path, CV accession, unit, ...), so a
spectrum element can be rebuilt without knowing which parameters a vendor uses.

Values that describe the peaks themselves (base peak, TIC, m/z range) are not
stored, because they would be wrong for reconstructed peaks. Only the fact that
the source spectrum had them is kept, and the writer recomputes them.
"""

from __future__ import annotations

import json
import math
import re
from typing import NamedTuple

import pyarrow as pa
from lxml import etree

MZML_NAMESPACE = "http://psi.hupo.org/ms/mzml"
COLUMN_PREFIX = "mzml:"
HEADER_KEY = b"spectrovq.mzml.header"
COLUMNS_KEY = b"spectrovq.mzml.columns"

BASE_PEAK_MZ = "MS:1000504"
BASE_PEAK_INTENSITY = "MS:1000505"
TOTAL_ION_CURRENT = "MS:1000285"
LOWEST_MZ = "MS:1000528"
HIGHEST_MZ = "MS:1000527"
DERIVED_ACCESSIONS = frozenset(
    {BASE_PEAK_MZ, BASE_PEAK_INTENSITY, TOTAL_ION_CURRENT, LOWEST_MZ, HIGHEST_MZ}
)

# Regenerated by the writer rather than stored.
_SKIPPED_SPECTRUM_ATTRS = frozenset({"index", "defaultArrayLength"})
_SKIPPED_TAGS = frozenset({"binaryDataArrayList"})

_SPECTRUM_START = re.compile(rb"<(?:\w+:)?spectrum\s")
_MZML_START = re.compile(rb"<mzML[\s>]")
_NUMBER = re.compile(r"-?(?:0|[1-9]\d*)(?:\.\d+)?(?:[eE][+-]?\d+)?")
_PREFIXED_INT = re.compile(r"(.*?)(0|[1-9]\d*)", re.DOTALL)


class ParamKey(NamedTuple):
    """Identity of one stored value: where it sits and how it is written."""

    path: str  # e.g. "scanList.0/scan.0"; "" is the spectrum element itself
    kind: str  # "cv", "user", "attr", "ref" or "node" (an empty element)
    name: str = ""
    accession: str = ""
    cv_ref: str = ""
    unit_cv_ref: str = ""
    unit_accession: str = ""
    unit_name: str = ""
    xsd_type: str = ""
    occurrence: int = 0  # the same parameter repeated within one element


def read_header(path: str, chunk_size: int = 1 << 16) -> str:
    """Return the text from ``<mzML`` up to the first spectrum, without parsing the file."""
    buffer = b""
    with open(path, "rb") as f:
        while (match := _SPECTRUM_START.search(buffer)) is None:
            chunk = f.read(chunk_size)
            if not chunk:
                raise ValueError(f"No spectrum found in {path}")
            buffer += chunk
    start = _MZML_START.search(buffer, 0, match.start())
    if start is None:
        raise ValueError(f"No <mzML> element found in {path}")
    header = buffer[start.start() : match.start()].decode("utf-8", errors="replace")
    if "xmlns=" not in header[: header.index(">")]:
        # Declared only on an <indexedmzML> wrapper, which is not part of the header.
        header = f'<mzML xmlns="{MZML_NAMESPACE}"{header[len("<mzML") :]}'
    return header


def flatten_spectrum(element) -> dict[ParamKey, str]:
    """Flatten a ``<spectrum>`` element into ``{ParamKey: value}``, skipping peak arrays."""
    values: dict[ParamKey, str] = {}
    _flatten(element, "", values)
    return values


def _local(element) -> str:
    return etree.QName(element).localname


def _flatten(element, path: str, values: dict[ParamKey, str]) -> None:
    tag = _local(element)
    is_root = path == ""
    has_content = False

    for name, value in element.attrib.items():
        if (is_root and name in _SKIPPED_SPECTRUM_ATTRS) or (
            tag.endswith("List") and name == "count"
        ):
            continue
        values[_intern(ParamKey(path, "attr", name))] = value
        has_content = True

    seen_params: dict[ParamKey, int] = {}
    seen_children: dict[str, int] = {}
    for child in element:
        if not isinstance(child.tag, str):  # comments, processing instructions
            continue
        child_tag = _local(child)
        if child_tag in _SKIPPED_TAGS:
            has_content = True
            continue
        key = _param_key(child, child_tag, path)
        if key is not None:
            occurrence = seen_params.get(key, 0)
            seen_params[key] = occurrence + 1
            value = child.get("value", "")
            if is_root and key.accession in DERIVED_ACCESSIONS:
                value = ""
            values[_intern(key._replace(occurrence=occurrence))] = value
        else:
            index = seen_children.get(child_tag, 0)
            seen_children[child_tag] = index + 1
            child_path = (
                f"{path}/{child_tag}.{index}" if path else f"{child_tag}.{index}"
            )
            _flatten(child, child_path, values)
        has_content = True

    if not has_content:
        values[_intern(ParamKey(path, "node"))] = ""


_interned_keys: dict[ParamKey, ParamKey] = {}


def _intern(key: ParamKey) -> ParamKey:
    """Share one key object between spectra: a run has few keys but many spectra."""
    return _interned_keys.setdefault(key, key)


def _param_key(child, tag: str, path: str) -> ParamKey | None:
    if tag == "cvParam":
        return ParamKey(
            path,
            "cv",
            child.get("name", ""),
            child.get("accession", ""),
            child.get("cvRef", ""),
            child.get("unitCvRef", ""),
            child.get("unitAccession", ""),
            child.get("unitName", ""),
        )
    if tag == "userParam":
        return ParamKey(
            path,
            "user",
            child.get("name", ""),
            unit_cv_ref=child.get("unitCvRef", ""),
            unit_accession=child.get("unitAccession", ""),
            unit_name=child.get("unitName", ""),
            xsd_type=child.get("type", ""),
        )
    if tag == "referenceableParamGroupRef":
        return ParamKey(path, "ref", child.get("ref", ""))
    return None


def _column_name(key: ParamKey, used: set[str]) -> str:
    base = re.sub(r"[^a-zA-Z0-9_\-]+", "_", key.name or key.path or "spectrum").strip(
        "_"
    )
    if key.kind == "user":
        base = f"opt_{base}"
    elif key.kind in ("ref", "node"):
        base = f"{key.kind}_{base}"
    name = f"{COLUMN_PREFIX}{base}"
    suffix = 1
    while name in used:
        suffix += 1
        name = f"{COLUMN_PREFIX}{base}_{suffix}"
    used.add(name)
    return name


def _encode_values(values: list[str | None]) -> tuple[pa.Array, str, str]:
    """Pick the most compact lossless type: returns (array, type name, integer prefix)."""
    present = [v for v in values if v is not None]
    if all(v == "" for v in present):
        return (
            pa.array([True if v is not None else None for v in values], pa.bool_()),
            "flag",
            "",
        )

    matches = [_PREFIXED_INT.fullmatch(v) for v in present]
    if all(matches) and len({m.group(1) for m in matches}) == 1:
        prefix = matches[0].group(1)
        try:
            array = pa.array(
                [None if v is None else int(v[len(prefix) :]) for v in values],
                pa.int64(),
            )
        except (OverflowError, pa.ArrowInvalid):
            array = None
        if array is not None:
            return array, "int", prefix

    if all(_NUMBER.fullmatch(v) and math.isfinite(float(v)) for v in present):
        return (
            pa.array([None if v is None else float(v) for v in values], pa.float64()),
            "float",
            "",
        )
    return pa.array(values, pa.string()), "str", ""


def encode_columns(
    rows: list[dict[ParamKey, str]],
) -> tuple[dict[str, pa.Array], bytes]:
    """Turn flattened spectra into Parquet columns and their JSON definitions."""
    keys: dict[ParamKey, None] = {}
    for row in rows:
        keys.update(dict.fromkeys(row))

    columns: dict[str, pa.Array] = {}
    definitions = []
    used: set[str] = set()
    for key in keys:
        array, value_type, prefix = _encode_values([row.get(key) for row in rows])
        name = _column_name(key, used)
        columns[name] = array
        definitions.append(
            {"column": name, "type": value_type, "prefix": prefix, **key._asdict()}
        )
    return columns, json.dumps(definitions).encode()


def load_definitions(raw: bytes) -> list[tuple[str, str, str, ParamKey]]:
    """Parse footer definitions into ``(column, type, prefix, key)``."""
    parsed = []
    for definition in json.loads(raw):
        column = definition.pop("column")
        value_type = definition.pop("type")
        prefix = definition.pop("prefix")
        parsed.append((column, value_type, prefix, ParamKey(**definition)))
    return parsed


def decode_row(
    row, definitions: list[tuple[str, str, str, ParamKey]]
) -> dict[ParamKey, str]:
    """Rebuild ``{ParamKey: value}`` for one spectrum from a metadata row."""
    values: dict[ParamKey, str] = {}
    for column, value_type, prefix, key in definitions:
        value = row[column]
        if value is None or (isinstance(value, float) and math.isnan(value)):
            continue
        if value_type == "flag":
            values[key] = ""
        elif value_type == "int":
            # A column with missing values comes back from pandas as float.
            values[key] = f"{prefix}{int(value)}"
        elif value_type == "float":
            values[key] = repr(float(value))
        else:
            values[key] = str(value)
    return values
